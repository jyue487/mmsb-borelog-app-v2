/** `utils/scaleticks.py` */
export function getYFromDepthInMetres(depthInMetres: number, pageNumber: number): number {
	const remainderInMetres = depthInMetres - (pageNumber - 1) * NUM_METRES_PER_PAGE;
	return BODY_Y_TOP - (remainderInMetres / NUM_METRES_PER_PAGE) * (BODY_Y_TOP - BODY_Y_BOTTOM);
}
